const langIdx=()=>LANG_ORDER.indexOf(LANG);
function t(key,vars){
  const e=I18N[key];let s=e?(e[langIdx()]||e[0]):key;
  if(vars)for(const k in vars)s=s.split("{"+k+"}").join(vars[k]);
  return s;
}
const _keys={};
function tv(type,val){
  if(LANG==="en"||val==null||val==="")return val;
  const d=VAL[type];if(!d)return val;
  const i=langIdx()-1,v=String(val);
  if(d[v])return d[v][i];
  const ks=_keys[type]||(_keys[type]=Object.keys(d).sort((a,b)=>b.length-a.length));
  let out=v;
  for(const k of ks){
    if(out.indexOf(k)<0)continue;
    const re=new RegExp((/^\w/.test(k)?"\\b":"")+k.replace(/[.*+?^${}()|[\]\\]/g,"\\$&")+(/\w$/.test(k)?"\\b":""),"g");
    out=out.replace(re,d[k][i]);
  }
  return out;
}
